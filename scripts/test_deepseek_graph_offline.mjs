import assert from 'node:assert/strict';
import {executeCall,checkPlan,TOOLS} from './test_deepseek_graph.mjs';
const data={scene:{title:'Project',groups:[],nodes:[{id:'client',label:'现场端',kind:'client'},{id:'service',label:'资料服务',kind:'service'}],edges:[{from:'client',to:'service'}]},presentation:{style:'手绘线稿',composition:'flow'}};
const document=executeCall('create_graph',data,null),before=JSON.stringify(document);
assert.throws(()=>executeCall('create_graph',data,document));
assert.throws(()=>executeCall('edit_graph',{operations:[{op:'rename_node',id:'service',label:'新名字'}]},null));
assert.throws(()=>executeCall('unknown',{},document));
assert.throws(()=>executeCall('edit_graph',{operations:[{op:'rename_node',id:'service',label:'Changed'},{op:'add_edge',edge:{from:'missing',to:'service'}}]},document));
assert.equal(JSON.stringify(document),before);
const changed=executeCall('edit_graph',{operations:[{op:'rename_node',id:'service',label:'资料接入'}]},document);
assert.equal(changed.scene.nodes[1].id,document.scene.nodes[1].id);
assert.deepEqual(changed.presentation,document.presentation);
assert.deepEqual(changed.scene.edges,document.scene.edges);
const task={style:'手绘线稿',states:[{nodes:['现场端','资料服务'],edges:[['现场端','资料服务']]}]};
assert.equal(checkPlan(task,0,document.scene,null).passed,true);
assert.equal(checkPlan(task,0,{...document.scene,edges:document.scene.edges.map(e=>({...e,direction:'none'}))},null).passed,false);
assert.equal(checkPlan(task,0,{...document.scene,edges:document.scene.edges.map(e=>({...e,id:'replacement'}))},document.scene).passed,false);
assert.equal(checkPlan(task,0,{...document.scene,edges:[]},null).passed,false);
assert.equal(checkPlan(task,0,{...document.scene,nodes:[...document.scene.nodes,{id:'invented',label:'Invented',kind:'service',parent:null}]},null).passed,false);
assert.equal(TOOLS.length,2);
console.log('PASS tool allowlist, lifecycle, atomic edits, stable identities and independent factual checks; network requests=0');
